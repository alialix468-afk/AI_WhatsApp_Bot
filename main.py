def call_groq_api(content, is_vision=False):
    url = "https://api.groq.com/openai/v1/chat/completions"
    headers = {"Authorization": f"Bearer {GROQ_API_KEY}", "Content-Type": "application/json"}
    
    # استخدام النموذج الذكي Vision للصور، و 70b للنصوص والصوت
    model_name = "llama-3.2-11b-vision-preview" if is_vision else "llama-3.3-70b-versatile"
    
    payload = {
        "model": model_name,
        "messages": [{"role": "system", "content": SYSTEM_PROMPT}, {"role": "user", "content": content}],
        "temperature": 0.7
    }
    resp = requests.post(url, headers=headers, json=payload)
    if resp.status_code == 200:
        return resp.json()["choices"][0]["message"]["content"]
    return "يا غالي، السيستم مشغول شوي، ارجع حاول مرة ثانية! [STICKER:ضحك]"

def transcribe_audio(audio_bytes):
    url = "https://api.groq.com/openai/v1/audio/transcriptions"
    headers = {"Authorization": f"Bearer {GROQ_API_KEY}"}
    files = {"file": ("audio.ogg", audio_bytes, "audio/ogg")}
    data = {"model": "whisper-large-v3-turbo"}
    
    resp = requests.post(url, headers=headers, files=files, data=data)
    if resp.status_code == 200:
        return resp.json().get("text", "")
    return "ما قدرت أسمع الصوت بوضوح."

@app.post("/webhook")
async def webhook(message: str = Form(None), audio: UploadFile = File(None), image: UploadFile = File(None)):
    try:
        user_text = message if message else ""
        
        # 1. معالجة الصوت (تحويله لنص)
        if audio:
            user_text = transcribe_audio(await audio.read())
            
        # 2. معالجة الصور/الملصقات
        if image:
            image_b64 = base64.b64encode(await image.read()).decode('utf-8')
            content = [
                {"type": "text", "text": user_text or "حلل هذه الصورة أو الملصق وأعطني رأيك بلهجة صنعانية"}, 
                {"type": "image_url", "image_url": {"url": f"data:image/jpeg;base64,{image_b64}"}}
            ]
            reply = call_groq_api(content, is_vision=True)
        else:
            # 3. معالجة النص العادي
            reply = call_groq_api(user_text)

        return {"reply": reply}
        
    except Exception as e:
        return {"reply": "يا لطيف، السيستم معلق شوية! [STICKER:ضحك]"}

